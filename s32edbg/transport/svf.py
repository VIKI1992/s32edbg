"""SVF emission and playback through JTAGLoad.exe.

An alternative route for the boundary-scan preamble. JTAGLoad is a genuine SVF
interpreter -- its dispatch table accepts HDR, HIR, SDR, SIR, TDR, TIR, ENDDR,
ENDIR, ENDSTATE, FREQUENCY, RUNTEST and STATE, with TDI/TDO/MASK/SMASK on scans
-- but it rejects three commands at runtime with these literal messages:

    Command "TRST" is not supported in this software version !
    Command "PIO" is not supported in this software version !
    Command "PIOMAP" is not supported in this software version !

so the emitter never produces them. It also selects JTAG unconditionally
("Selecting JTAG as target interface"), which suits this target since the port
comes out of reset in JTAG anyway.

None of this is documented in the UM08001 shipped with the tool; it was read out
of the JTAGLoad.exe binary and cross-checked against the release notes.
"""

from __future__ import annotations

import subprocess
from dataclasses import dataclass
from pathlib import Path

from ..errors import TransportError
from .install import JLinkInstall, discover

#: Commands JTAGLoad parses but refuses. Emitting one aborts the file.
UNSUPPORTED_SVF_COMMANDS = ("TRST", "PIO", "PIOMAP")


def _hex(value: int, nbits: int) -> str:
    return f"{value:0{(nbits + 3) // 4}X}"


def emit_svf(
    steps: list[tuple[str, int, int, int, int]],
    ir_length: int,
    *,
    frequency_hz: int | None = None,
    comment: str | None = None,
) -> str:
    """Render (label, opcode8, ir_value, dr_value, dr_bits) steps as SVF.

    ``ENDIR``/``ENDDR`` are set to IDLE so each scan returns to Run-Test/Idle,
    matching what the raw-shift path does and keeping the loaded instruction
    selected between an SIR and its following SDR.

    ``ir_length`` is passed in rather than inferred from how big the opcode
    happens to be. Inference works for the three preamble opcodes -- 0x0A00,
    0x2121, 0x2020 all exceed 0xFF -- and then silently fails for RM Table 959's
    16-bit IDCODE, which is 0x0001 and would be emitted as an 8-bit SIR. A scan
    of the wrong width does not error; it selects a different register, which is
    precisely how the 8-bit preamble came to look like it worked while actually
    reading the device ID.
    """
    lines: list[str] = []
    if comment:
        for line in comment.splitlines():
            lines.append(f"! {line}")
    lines.append("! Generated by s32edbg. TRST/PIO/PIOMAP are omitted: JTAGLoad rejects them.")
    if frequency_hz:
        lines.append(f"FREQUENCY {frequency_hz:d} HZ;")
    lines.append("ENDIR IDLE;")
    lines.append("ENDDR IDLE;")
    lines.append("STATE RESET;")
    lines.append("STATE IDLE;")

    for label, _opcode8, ir_value, dr_value, dr_bits in steps:
        lines.append(f"! {label}")
        lines.append(f"SIR {ir_length} TDI ({_hex(ir_value, ir_length)});")
        lines.append(f"SDR {dr_bits} TDI ({_hex(dr_value, dr_bits)});")

    return "\n".join(lines) + "\n"


def emit_svf_for_preamble(ir_length: int, *, frequency_hz: int | None = None) -> str:
    from ..data.bscan import preamble_steps

    steps = preamble_steps(ir_length)
    return emit_svf(
        steps,
        ir_length,
        frequency_hz=frequency_hz,
        comment=(
            "S32E2 boundary-scan preamble, RM Table 984.\n"
            "Selects the BSR segments for this package before SAMPLE/PRELOAD."
        ),
    )


def emit_dr_read(
    ir_length: int,
    ir_value: int,
    nbits: int,
    byte_index: int,
    *,
    frequency_hz: int | None = None,
    with_preamble: bool = True,
    tdi: int = 0,
) -> str:
    """SVF that loads ``ir_value`` and reads one byte of its data register.

    JTAGLoad has no "print TDO" command -- the only way it ever reveals received
    data is the mismatch report:

        Received wrong TDO data from target! (Expected: 0x00, Found: 0x1D)

    So a read is a deliberately-failing compare: expect zero, mask exactly the
    byte of interest, and let the reported "Found" value be the answer. A byte
    that really is zero produces no report, which reads back as zero correctly.
    One byte per invocation, because JTAGLoad stops at the first mismatch.

    ``byte_index`` counts from the first bit shifted out. SVF writes its scan
    values MSB-first across the whole vector, so byte 0 is the *rightmost* pair
    of hex digits -- hence the reversed position below.
    """
    if nbits % 8:
        raise ValueError(
            f"a byte-masked read needs a whole number of bytes, not {nbits} bits; "
            "round the scan up and discard the tail"
        )
    nbytes = nbits // 8
    if not 0 <= byte_index < nbytes:
        raise ValueError(f"byte_index {byte_index} outside a {nbits}-bit scan")

    mask = ["00"] * nbytes
    mask[nbytes - 1 - byte_index] = "FF"

    lines: list[str] = []
    if with_preamble:
        lines.append(emit_svf_for_preamble(ir_length, frequency_hz=frequency_hz).rstrip("\n"))
    else:
        lines.append("! Generated by s32edbg.")
        if frequency_hz:
            lines.append(f"FREQUENCY {frequency_hz:d} HZ;")
        lines += ["ENDIR IDLE;", "ENDDR IDLE;", "STATE RESET;", "STATE IDLE;"]

    lines.append(f"SIR {ir_length} TDI ({_hex(ir_value, ir_length)});")
    lines.append(
        f"SDR {nbits} TDI ({_hex(tdi, nbits)}) "
        f"TDO ({_hex(0, nbits)}) "
        f"MASK ({''.join(mask)});"
    )
    return "\n".join(lines) + "\n"


#: JTAGLoad's mismatch report, which doubles as its only read channel.
TDO_MISMATCH = "Received wrong TDO data from target!"


def parse_found_byte(stdout: str) -> int | None:
    """The "Found: 0x.." value from a TDO mismatch, or None if none was reported."""
    import re

    m = re.search(r"Found:\s*0x([0-9A-Fa-f]+)", stdout)
    return int(m.group(1), 16) if m else None


@dataclass
class SvfResult:
    returncode: int
    stdout: str
    command: list[str]

    @property
    def ok(self) -> bool:
        return self.returncode == 0 and "Download successful." in self.stdout

    def failures(self) -> list[str]:
        bad: list[str] = []
        for line in self.stdout.splitlines():
            low = line.lower()
            if "not supported" in low or "could not" in low or "failed" in low or "mismatch" in low:
                bad.append(line.strip())
        return bad


def run_svf(
    path: str | Path,
    *,
    install: JLinkInstall | None = None,
    serial: str | None = None,
    log_file: str | Path | None = None,
    timeout: float = 120.0,
) -> SvfResult:
    """Play an SVF file with JTAGLoad.exe."""
    inst = install or discover()
    exe = inst.jtagload
    if not exe.is_file():
        raise TransportError(f"JTAGLoad.exe not found at {exe}")

    argv = [str(exe)]
    if serial:
        argv += ["-USB", serial]
    if log_file:
        argv += ["-LogFile", str(log_file)]
    argv.append(str(path))

    try:
        proc = subprocess.run(
            argv,
            capture_output=True,
            text=True,
            timeout=timeout,
            cwd=str(inst.path),
            encoding="utf-8",
            errors="replace",
        )
    except subprocess.TimeoutExpired as exc:
        raise TransportError(f"JTAGLoad timed out after {timeout:.0f}s") from exc
    except OSError as exc:
        raise TransportError(f"could not run {exe}: {exc}") from exc

    return SvfResult(returncode=proc.returncode, stdout=proc.stdout + proc.stderr, command=argv)
